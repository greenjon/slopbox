#!/usr/bin/env python3
# Writes docs/manual/menu-tree.md: the Settings menu as SlopBox shows it (Rockbox's menus from
# app/src/main/assets/rockbox_settings.json plus the SlopBox menu), marking the settings SlopBox
# doesn't act on yet (shown dimmed in the app). Run after regenerating the settings JSON.
# SPDX-License-Identifier: GPL-2.0-or-later
import json, os, re

root = os.path.join(os.path.dirname(__file__), "..")
d = json.load(open(os.path.join(root, "app/src/main/assets/rockbox_settings.json")))
src = open(os.path.join(root, "app/src/main/java/llm/slop/slopbox/RockboxSettings.kt")).read()

def strings(block_start):
    i = src.index(block_start)
    depth, j = 0, src.index("(", i)
    for k in range(j, len(src)):
        if src[k] == "(": depth += 1
        elif src[k] == ")":
            depth -= 1
            if depth == 0: return set(re.findall(r'"([^"]+)"', src[j:k]))
    return set()

live = strings("val ENGINE_IDS = listOf") | strings("val PLAYER_SETTINGS = setOf")
consts = dict(re.findall(r'const val (\w+) = "([^"]+)"', src))
live |= {consts[n] for n in re.findall(r"SlopBoxSettings\.(\w+)", src[src.index("val PLAYER_SETTINGS"):]) if n in consts}
settings = d["settings"]

def text(x):
    v = x.get("text")
    return v.get("text") if isinstance(v, dict) else v

out = ["# Settings menu", "",
       "Every item in SlopBox's Settings menu, in order. Settings marked *(not used yet)* are",
       "shown dimmed in the app: they're saved with your other settings but SlopBox doesn't",
       "act on them yet. Items marked → open a screen or run an action rather than",
       "holding a value. This page is generated by `scripts/manual_menu_tree.py`.", ""]

def walk(m, depth):
    for it in m.get("items", []):
        t = text(it)
        s = settings[it["setting"]] if it.get("setting", -1) >= 0 and it["setting"] < len(settings) else None
        if s and not t: t = (s.get("title") or {}).get("text") if isinstance(s.get("title"), dict) else s.get("title")
        if not t and s: t = s["cfg"]
        if not t and it.get("text_fn") == "wps_context_menu_get_name":
            n = int((it.get("param") or "?0")[1:])
            t = d["lang"]["LANG_HOTKEY_WPS"] if n == 0 else f'{d["lang"]["LANG_SET_CONTEXT_ITEM"]} {n}'
        if not t and it.get("text_fn") == "sleeptimer_getname":
            t = d["lang"]["LANG_SLEEP_TIMER"]
        line = "  " * depth + "- "
        if it["type"] == 0:
            line += f"**{t}**"
        elif it["type"] in (1, 2) and s:
            line += t + ("" if s["cfg"] in live or s["cfg"].startswith("eq filter") else " *(not used yet)*")
        else:
            line += f"{t} →"
        out.append(line)
        if it["type"] == 0: walk(it, depth + 1)

walk(d["menu"], 0)
# SlopBox's own menu, added under Theme Settings in the app.
out += ["", "SlopBox adds a **SlopBox** menu at the end of Theme Settings:", "",
        "- **SlopBox**", "  - **Now Playing Gestures**"]
names = re.findall(r'Bool\((\w+), "([^"]+)"|Choice\((\w+), "([^"]+)"', src)
items = [(a or c, b or e) for a, b, c, e in names]
for n, (c, t) in enumerate(items):
    out.append(("    - " if n < 5 else "  - ") + t)
open(os.path.join(root, "docs/manual/menu-tree.md"), "w").write("\n".join(out) + "\n")
print("wrote docs/manual/menu-tree.md")
